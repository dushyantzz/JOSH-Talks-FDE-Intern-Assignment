hyps = {}

for c in picked:
    wav = f"{c['uri']}.wav"

    # Pyannote 3.1 (blind)
    hyps[("pyannote-3.1 (blind)", c["uri"])] = pipe(wav)

    # Pyannote 3.1 (oracle speaker count)
    hyps[("pyannote-3.1 (oracle #spk)", c["uri"])] = pipe(
        wav,
        num_speakers=c["n_spk"]
    )

print("Done:", len(hyps), "runs")

import pandas as pd
from pyannote.core import Timeline
from pyannote.metrics.diarization import DiarizationErrorRate, JaccardErrorRate

rows = []
for (system, uri), hyp in hyps.items():
    c = next(x for x in picked if x["uri"] == uri)
    uem = Timeline([Segment(0, c["dur"])])
    row = dict(clip=uri, system=system, dur_s=round(c["dur"]), ref_spk=c["n_spk"],
               hyp_spk=len(hyp.labels()), overlap=f"{c['overlap']:.1%}")
    for name, kw in {"strict": dict(collar=0.0, skip_overlap=False),
                     "lenient": dict(collar=0.25, skip_overlap=True)}.items():
        d = DiarizationErrorRate(**kw)(c["ref"], hyp, uem=uem, detailed=True)
        row[f"DER_{name}"] = round(100 * d["diarization error rate"], 1)
        if name == "strict":
            row["miss%"] = round(100 * d["missed detection"] / d["total"], 1)
            row["FA%"] = round(100 * d["false alarm"] / d["total"], 1)
            row["conf%"] = round(100 * d["confusion"] / d["total"], 1)
    row["JER_strict"] = round(100 * JaccardErrorRate(collar=0.0, skip_overlap=False)(c["ref"], hyp, uem=uem), 1)
    rows.append(row)

res = pd.DataFrame(rows).sort_values(["clip", "system"])
display(res); res.to_csv("results.csv", index=False)

